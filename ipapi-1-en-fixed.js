const citytest = /[a-zA-Z]+[a-zA-Z]+/;
function longCheck(...paragraphs) {
  const validParagraphs = paragraphs.filter((para) => para.length > 1 && para.length < 31);
  return validParagraphs.length > 0 ? validParagraphs[0] : paragraphs[paragraphs.length - 1];
}
function letterCheck(para, paraa, paraaa) {
  const testParagraphs = [para, paraa, paraaa].filter((p) => !citytest.test(p) && p.length > 1);
  return testParagraphs[0] || paraaa;
}
function placeAdder(para) {
  return para && !citytest.test(para) ? ` ${para}` : "";
}
function geticon(para, paraa) {
  return para ? `${paraa} ` : "";
}
